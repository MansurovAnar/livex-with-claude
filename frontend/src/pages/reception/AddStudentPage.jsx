import React, { useState } from 'react';
import { createStudent } from '../../api/students.api';
import useStudentEmailPreview from '../../hooks/useStudentEmailPreview';

const PREFIXES = ['010', '050', '051', '055', '070', '077', '099'];
const CLASSES = Array.from({ length: 11 }, (_, i) => i + 1);
const SECTORS = ['Azerbaijan', 'Rus'];
const LANGUAGES = ['English', 'Russian', 'German', 'French'];
const emptyForm = { student_number: '', first_name: '', last_name: '', father_name: '', mobile_prefix: '050', mobile_number: '', class_level: '', sector: '', language: '' };

export default function AddStudentPage() {
  const [form, setForm] = useState(emptyForm);
  const [success, setSuccess] = useState(null);
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(false);
  const [previewKey, setPreviewKey] = useState(0);
  const emailPreview = useStudentEmailPreview('/students/email-preview', form.first_name, form.last_name, previewKey);

  const handleChange = e => setForm(f => ({ ...f, [e.target.name]: e.target.value }));

  const handleSubmit = async (e) => {
    e.preventDefault();
    setError(''); setSuccess(null); setLoading(true);
    try {
      const fullMobile = form.mobile_number ? `${form.mobile_prefix}${form.mobile_number}` : undefined;
      const payload = {
        student_number: form.student_number,
        first_name: form.first_name,
        last_name: form.last_name,
        ...(form.father_name.trim() && { father_name: form.father_name }),
        ...(fullMobile && { mobile_number: fullMobile }),
        ...(form.class_level && { class_level: Number(form.class_level) }),
        ...(form.sector && { sector: form.sector }),
        ...(form.language && { language: form.language }),
      };
      const res = await createStudent(payload);
      setSuccess(res.data.data);
      setForm(emptyForm);
      setPreviewKey(k => k + 1);
    } catch (err) {
      setError(err.response?.data?.error?.message || 'Failed to add student');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div style={{ maxWidth: 480 }}>
      <h2>Add New Student</h2>
      {success && (
        <div style={{ background: '#f0fdf4', border: '1px solid #86efac', padding: '0.75rem', borderRadius: 6, marginBottom: '1rem' }}>
          Student <strong>{success.full_name}</strong> added successfully. ID: {success.student_number}
          <div className="wrap-text">Email: <strong>{success.email}</strong></div>
        </div>
      )}
      {error && <div style={{ background: '#fef2f2', color: '#dc2626', padding: '0.75rem', borderRadius: 6, marginBottom: '1rem' }}>{error}</div>}

      <form onSubmit={handleSubmit} style={{ background: '#fff', padding: '1.5rem', borderRadius: 8, border: '1px solid #e2e8f0' }}>

        {[
          { name: 'student_number', label: 'Student Number', type: 'text', required: true, maxLength: 7 },
          { name: 'first_name', label: 'Name', type: 'text', required: true, maxLength: 50 },
          { name: 'last_name', label: 'Surname', type: 'text', required: true, maxLength: 50 },
          { name: 'father_name', label: 'Father Name', type: 'text', required: false, maxLength: 50 },
        ].map(f => (
          <div key={f.name} style={{ marginBottom: '1rem' }}>
            <label style={labelStyle}>{f.label}{f.required && <span style={{ color: '#dc2626' }}> *</span>}</label>
            <input type={f.type} name={f.name} value={form[f.name]} onChange={handleChange} required={f.required}
              maxLength={f.maxLength} style={inputStyle} />
          </div>
        ))}

        {/* Email — generated by the server from name + first letter of surname */}
        <div style={{ marginBottom: '1rem' }}>
          <label style={labelStyle}>Email</label>
          <input type="text" value={emailPreview} readOnly placeholder="Generated from name and surname" title="Generated automatically"
            style={{ ...inputStyle, background: '#f1f5f9', color: '#475569', cursor: 'not-allowed' }} />
        </div>

        {/* Mobile with prefix */}
        <div style={{ marginBottom: '1.25rem' }}>
          <label style={labelStyle}>Mobile Number</label>
          <div style={{ display: 'flex', gap: '0.5rem' }}>
            <select
              name="mobile_prefix"
              value={form.mobile_prefix}
              onChange={handleChange}
              style={{ ...inputStyle, width: 90, flex: 'none' }}
            >
              {PREFIXES.map(p => <option key={p} value={p}>{p}</option>)}
            </select>
            <input
              type="tel"
              name="mobile_number"
              value={form.mobile_number}
              onChange={handleChange}
              placeholder="XXXXXXX"
              maxLength={7}
              style={inputStyle}
            />
          </div>
        </div>

        <div style={{ marginBottom: '1rem' }}>
          <label style={labelStyle}>Class</label>
          <select name="class_level" value={form.class_level} onChange={handleChange} style={inputStyle}>
            <option value="">Select class...</option>
            {CLASSES.map(c => <option key={c} value={c}>{c}</option>)}
          </select>
        </div>

        <div style={{ marginBottom: '1rem' }}>
          <label style={labelStyle}>Language</label>
          <select name="language" value={form.language} onChange={handleChange} style={inputStyle}>
            <option value="">Select language...</option>
            {LANGUAGES.map(l => <option key={l} value={l}>{l}</option>)}
          </select>
        </div>

        <div style={{ marginBottom: '1.25rem' }}>
          <label style={labelStyle}>Sector</label>
          <div style={{ display: 'flex', gap: '1.5rem', flexWrap: 'wrap', alignItems: 'center' }}>
            {SECTORS.map(s => (
              <label key={s} style={{ display: 'flex', alignItems: 'center', gap: '0.4rem', cursor: 'pointer', fontSize: '0.875rem', fontWeight: 500, color: '#374151' }}>
                <input type="radio" name="sector" value={s} checked={form.sector === s} onChange={handleChange} style={{ width: 16, height: 16 }} />
                {s}
              </label>
            ))}
            {form.sector && (
              <button type="button" onClick={() => setForm(f => ({ ...f, sector: '' }))}
                style={{ background: 'none', border: 'none', color: '#94a3b8', cursor: 'pointer', fontSize: '0.8rem' }}>
                Clear
              </button>
            )}
          </div>
        </div>

        <button type="submit" disabled={loading}
          style={{ width: '100%', padding: '0.6rem', background: '#7e22ce', color: '#fff', border: 'none', borderRadius: 4, fontSize: '1rem', cursor: loading ? 'not-allowed' : 'pointer', opacity: loading ? 0.7 : 1 }}>
          {loading ? 'Adding...' : 'Add Student'}
        </button>
      </form>
    </div>
  );
}

const inputStyle = { width: '100%', padding: '0.5rem 0.75rem', border: '1px solid #cbd5e1', borderRadius: 4, fontSize: '1rem', boxSizing: 'border-box' };
const labelStyle = { display: 'block', fontWeight: 500, marginBottom: '0.25rem', fontSize: '0.875rem', color: '#374151' };
